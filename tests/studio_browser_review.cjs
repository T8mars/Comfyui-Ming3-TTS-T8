// Browser regression against the local studio; API responses are controlled, no inference runs.
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const root = path.resolve(__dirname, "..");
const output = path.join(root, ".publishing", "review-browser");
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.EDGE_EXE || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe" });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    const errors = []; page.on("pageerror", error => errors.push(error.message));
    const jobs = [];
    const watchedJobs = [];
    let updateState = {status:"idle",message:"尚未检查程序更新",current_version:"0.2.0",managed:true,automatic:true};
    let serial = 0, cropGate = null, cropStarted = false;
    let importedProject = {request:{task:"seed",text:"新工程的正文",prompt_wav:"imported.wav",prompt_text:"新工程对应文字",target_language:"Chinese"}};
    const reference = (name = "prepared.wav") => ({ path: name, name, seconds: 2, start: 0, end: 2, waveform: [] });
    await page.route("**/studio/app.js", route => route.fulfill({ contentType: "text/javascript", body: fs.readFileSync(path.join(root, "studio/app.js"), "utf8") }));
    await page.route("**/api/**", async route => {
      const request = route.request(), url = new URL(request.url());
      let value = {};
      if (url.pathname === "/api/voices") value = { ...JSON.parse(fs.readFileSync(path.join(root, "ming_t8/assets/voices.json"))), saved: [{ id: "review-saved", ...reference("saved.wav"), text: "收藏声音的对应文字" }] };
      else if (url.pathname === "/api/status") value = { model: { ready: true, download_fraction: 1 }, asr: { available: true }, download: { status: "idle" }, data_root: "review", python: "3.12", updates:updateState };
      else if (url.pathname === "/api/settings") value = {model_path:"model.safetensors",assets_path:"assets",asr_root:"confucius",native_kernels:"auto",attention_backend:"sdpa",cuda_graphs:true};
      else if (url.pathname === "/api/updates/check") value = updateState = {...updateState,status:"available",latest_version:"0.2.1",message:"发现程序更新 0.2.1"};
      else if (url.pathname === "/api/updates/download") value = updateState = {...updateState,status:"ready",message:"程序更新已下载，关闭工作台后重新启动即可安装"};
      else if (url.pathname === "/api/updates/preferences") value = updateState = {...updateState,automatic:request.postDataJSON().automatic};
      else if (url.pathname === "/api/updates") value = updateState;
      else if (url.pathname === "/api/audio/upload") value = reference(`upload-${++serial}.wav`);
      else if (url.pathname === "/api/audio/prepare") {
        if (cropGate) { cropStarted = true; await cropGate; }
        value = reference(`prepared-${++serial}.wav`);
      } else if (url.pathname === "/api/jobs" && request.method() === "POST") {
        const payload = request.postDataJSON();
        value = { id: `job-${++serial}`, status: "queued", payload, created_at: Date.now(), message: "已排队" };
        jobs.unshift({ ...value, status: "complete", result: { text: "旧录音的自动转写" } });
      } else if (url.pathname === "/api/jobs") { value = jobs; watchedJobs.push(url.searchParams.get("watch")); }
      else if (url.pathname === "/api/projects/import") value = importedProject;
      else if (url.pathname === "/api/audio/inspect") value = reference(request.postDataJSON().path);
      else if (url.pathname === "/api/audio/file") return route.fulfill({ status: 204 });
      await route.fulfill({ json: value });
    });
    await page.goto(process.env.MING_STUDIO_URL || "http://127.0.0.1:7863/");
    await page.locator("#task").selectOption("seed");
    const upload = () => page.locator("#reference-upload").setInputFiles({ name: "reference.wav", mimeType: "audio/wav", buffer: Buffer.from("test audio") });
    const createPendingTranscript = async () => {
      await upload();
      await page.locator("#reference-detail").waitFor({ state: "visible" });
      await page.locator("#transcript").fill("手工核对后的文字");
      await page.locator("#transcribe-reference").click();
      await page.locator("#adopt-machine").waitFor({ state: "visible" });
      assert.equal(await page.locator("#transcript").inputValue(), "手工核对后的文字");
    };
    await createPendingTranscript();
    await page.locator("#crop-end").fill("1");
    await page.locator("#apply-crop").click();
    await page.waitForFunction(() => document.getElementById("transcript").value === "");
    assert.equal(await page.locator("#adopt-machine").isVisible(), false);
    await createPendingTranscript();
    await page.locator("#clear-reference").click();
    assert.equal(await page.locator("#reference-detail").isVisible(), false);
    await createPendingTranscript();
    await page.locator("#advanced > summary").click();
    await page.locator("#cfg").fill("7");
    await page.locator("#flow-steps").fill("32");
    await page.locator("#seed").fill("99");
    await page.locator("#project-file").setInputFiles({name:"project.mingstudio.zip",mimeType:"application/zip",buffer:Buffer.from("controlled project import")});
    await page.waitForFunction(() => document.getElementById("transcript").value === "新工程对应文字" && document.getElementById("cfg").value === "2");
    assert.equal(await page.locator("#flow-steps").inputValue(), "10");
    assert.equal(await page.locator("#seed").inputValue(), "");
    assert.equal(await page.locator("#stop-threshold").inputValue(), "");
    assert.equal(await page.locator("#adopt-machine").isVisible(), false);
    assert.ok(watchedJobs.some(value => value && value.includes("job-")), "focused and callback jobs must stay watched");
    await upload();
    await page.locator("#reference-detail").waitFor({ state: "visible" });
    assert.equal(await page.locator("#adopt-machine").isVisible(), false);
    await page.locator('[data-view="library"]').click();
    await page.locator('#saved-voices [data-saved-voice="review-saved"]').click();
    assert.equal(await page.locator("#transcript").inputValue(), "收藏声音的对应文字");
    assert.match(await page.locator("#reference-player").getAttribute("src"), /saved.wav/);
    await page.locator('[data-view="dialogue"]').click();
    await page.locator("[data-role-saved]").first().click();
    await page.locator("#saved-dialog").waitFor({ state: "visible" });
    await page.keyboard.press("Escape");
    await page.locator('[data-view="library"]').click();
    await page.locator('#saved-voices [data-saved-voice="review-saved"]').click();
    assert.equal(await page.locator("#reference-player").isVisible(), true);
    assert.equal(await page.locator("#transcript").inputValue(), "收藏声音的对应文字");
    let releaseCrop;
    cropGate = new Promise(resolve => { releaseCrop = resolve; });
    await page.locator("#apply-crop").click();
    await page.waitForTimeout(100);
    assert.equal(cropStarted, true);
    await page.locator("#clear-reference").click();
    releaseCrop();
    await page.waitForTimeout(150);
    assert.equal(await page.locator("#reference-detail").isVisible(), false);
    await page.screenshot({ path: path.join(output, "desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(output, "mobile.png"), fullPage: true });
    await page.locator("#model-status").click();
    await page.locator("#settings-dialog").waitFor({state:"visible"});
    assert.match(await page.locator("#update-version").textContent(), /0.2.0/);
    await page.locator("#check-program-update").click();
    await page.locator("#download-program-update").waitFor({state:"visible"});
    await page.locator("#download-program-update").click();
    await page.waitForFunction(() => document.getElementById("update-message").textContent.includes("重新启动"));
    await page.locator("#auto-program-update").uncheck();
    assert.equal(updateState.automatic, false);
    await page.screenshot({path:path.join(output,"update-settings-mobile.png"),fullPage:true});
    await page.locator('[data-close-dialog="settings-dialog"]').click();
    importedProject = {request:{task:"podcast",text:"speaker_1: 你好。\nspeaker_2: 很高兴见到你。",prompt_wav:["a.wav","b.wav"],prompt_text:["甲的录音","乙的录音"],seed:23},
      characters:[{id:"a",name:"甲",prompt_wav:"a.wav",prompt_text:"甲的录音"},{id:"b",name:"乙",prompt_wav:"b.wav",prompt_text:"乙的录音"}]};
    await page.locator("#project-file").setInputFiles({name:"podcast.mingstudio.zip",mimeType:"application/zip",buffer:Buffer.from("controlled podcast project")});
    await page.locator("#dialogue-card").waitFor({state:"visible"});
    assert.equal(await page.locator("[data-line-text]").count(), 2);
    assert.equal(await page.locator("[data-line-text]").first().inputValue(), "你好。");
    assert.equal(await page.locator('[aria-label="角色名称"]').first().inputValue(), "甲");
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, "result.json"), JSON.stringify({ passed: true, browser: await browser.version(), cases: ["manual transcript protected", "crop clears stale ASR", "clear and replacement clear stale ASR", "saved voice wins over existing draft", "closed role picker cannot redirect a later choice", "late crop cannot resurrect reference", "390px layout", "no page errors", "program version", "check and download", "restart notice", "disable automatic updates", "project clears previous ASR candidate", "poll watches focused and callback jobs", "omitted project controls restore official defaults", "podcast character metadata without UI retains script"], inference: "not run; controlled API responses" }, null, 2));
    console.log("Browser review passed: reference state, saved voice, late responses, desktop/mobile, no page errors");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
